package my.project.telegrambotservice.support.dialog;

/**
 * Шаги, которые проходит пользователь, пока заполняет обращение.
 */
public enum DialogStep {

	/** Выбор темы кнопкой. */
	CATEGORY,
	/** Название и адрес ресторана (только для темы «Вопрос от ресторана»). */
	RESTAURANT,
	/** Описание проблемы или вопроса. */
	DESCRIPTION,
	/** Скриншоты и файлы — необязательный шаг. */
	ATTACHMENTS,
	/** Email аккаунта на сайте — необязательный шаг. */
	EMAIL,
	/** Проверка и отправка. */
	CONFIRM
}
